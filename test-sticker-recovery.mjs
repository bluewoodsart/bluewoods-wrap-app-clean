import assert from 'node:assert/strict';
import {deflateSync} from 'node:zlib';
import {crc32,validateCanvasPng} from './server/sticker-png.mjs';
import * as recovery from './server/sticker-recovery.mjs';
import {pngFixture,join} from './test-sticker-fixtures.mjs';
import {checkRecovery} from './test-sticker-recovery-cases.mjs';
const pixels=new Uint8Array((1200*4+1)*1200);
const fixture=pngFixture(crc32,deflateSync(pixels));
assert.equal(validateCanvasPng(fixture.bytes),fixture.bytes);
assert.throws(()=>validateCanvasPng(fixture.bytes.slice(0,33)));
assert.throws(()=>validateCanvasPng(fixture.bytes.slice(0,-1)));
assert.throws(()=>validateCanvasPng(join(fixture.bytes,Uint8Array.of(1))));
const corrupt=fixture.bytes.slice();corrupt[29]^=1;assert.throws(()=>validateCanvasPng(corrupt));
assert.throws(()=>validateCanvasPng(pngFixture(crc32,deflateSync(pixels),{width:1199}).bytes));
assert.throws(()=>validateCanvasPng(pngFixture(crc32,Uint8Array.of(1,2,3)).bytes));
assert.throws(()=>validateCanvasPng(pngFixture(crc32,deflateSync(pixels.slice(1))).bytes));
assert.throws(()=>validateCanvasPng(pngFixture(crc32,deflateSync(new Uint8Array(pixels.length+1))).bytes));
pixels[0]=5;assert.throws(()=>validateCanvasPng(pngFixture(crc32,deflateSync(pixels)).bytes));
const rgb=new Uint8Array((1200*3+1)*1200);validateCanvasPng(pngFixture(crc32,deflateSync(rgb),{color:2}).bytes);
const passed=await checkRecovery(recovery,(condition,message)=>assert(condition,message));
console.log('PASS native PNG validation and recovery:',passed);
